-- Dedicated role for dbt: read RAW, full control of STAGING and MARTS.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS OLIST_DBT_ROLE;

GRANT USAGE, OPERATE ON WAREHOUSE OLIST_WH TO ROLE OLIST_DBT_ROLE;
GRANT USAGE ON DATABASE OLIST TO ROLE OLIST_DBT_ROLE;

-- RAW is read-only for dbt.
GRANT USAGE ON SCHEMA OLIST.RAW TO ROLE OLIST_DBT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA OLIST.RAW TO ROLE OLIST_DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA OLIST.RAW TO ROLE OLIST_DBT_ROLE;

-- dbt builds its models in STAGING and MARTS.
GRANT ALL PRIVILEGES ON SCHEMA OLIST.STAGING TO ROLE OLIST_DBT_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA OLIST.MARTS TO ROLE OLIST_DBT_ROLE;

-- Give the role to the user running this script.
SET me = CURRENT_USER();
GRANT ROLE OLIST_DBT_ROLE TO USER IDENTIFIER($me);
